"""Generate the requirements files from ``pyproject.toml``.

Run after changing a dependency:

    python tools/sync_requirements.py

Why generate rather than maintain by hand
-----------------------------------------

Because two lists of dependencies drift, and the drift is silent. This repository exists
because generic code drifted out of one repository into three others; a hand-written
``requirements.txt`` beside a ``pyproject.toml`` is the same failure in miniature — the
day someone bumps ``numpy>=1.26`` in one and not the other, the conda user and the pip
user are running different libraries and nothing says so.

So ``pyproject.toml`` is the single source of truth, these files are derived from it, and
``tests/test_requirements.py`` fails if they are stale. That test is the point of the
arrangement: it converts "remember to update both" into a red test.
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PYPROJECT = ROOT / "pyproject.toml"

HEADER = (
    "# GENERATED by tools/sync_requirements.py from pyproject.toml — do not edit.\n"
    "# Change the dependency in pyproject.toml, then re-run:\n"
    "#     python tools/sync_requirements.py\n"
    "# tests/test_requirements.py fails if this file is out of date.\n"
)


#: PyPI name -> conda-forge name, where they differ. Empty for this project's
#: dependencies (pyyaml, scikit-learn and the rest carry the same name on both), but the
#: indirection is here so that a future dependency which does differ has an obvious home
#: rather than being silently wrong.
CONDA_NAMES: dict[str, str] = {}

#: Build-backend packages. Not runtime dependencies, so they are not in pyproject's
#: dependency lists — but they are what an editable install has to build with, and having
#: conda place them is what lets that install run offline.
CONDA_BUILD_TOOLS = ("hatchling", "editables")


def _conda_specs(core: list[str], extras: dict[str, list[str]]) -> list[str]:
    """Conda match specs for everything a working environment needs.

    The version constraints are pyproject's, unchanged: `numpy>=1.26` is valid in both
    grammars. Only the *name* can differ between PyPI and conda-forge, which is what
    :data:`CONDA_NAMES` is for.
    """
    wanted: list[str] = [*core, *extras.get("dev", []), *extras.get("tutorial", [])]
    specs: list[str] = []
    seen: set[str] = set()
    for requirement in wanted:
        name, _, constraint = requirement.partition(">")
        name = name.strip()
        conda_name = CONDA_NAMES.get(name, name)
        if conda_name in seen:
            continue
        seen.add(conda_name)
        specs.append(f"{conda_name}>{constraint}" if constraint else conda_name)
    return specs + [tool for tool in CONDA_BUILD_TOOLS if tool not in seen]


def load() -> dict:
    with PYPROJECT.open("rb") as handle:
        return tomllib.load(handle)


def _block(lines: list[str]) -> str:
    return "\n".join(lines).rstrip() + "\n"


def render(config: dict) -> dict[str, str]:
    """The content of every generated file, keyed by path relative to the repo root."""
    project = config["project"]
    core = project["dependencies"]
    extras = project.get("optional-dependencies", {})
    python = project["requires-python"]

    files: dict[str, str] = {}

    # -- the core runtime ---------------------------------------------------
    files["requirements.txt"] = _block(
        [
            HEADER,
            "# The core runtime. Deliberately small: no darts, no torch, no",
            "# transformers, no safetycage. Everything heavier is optional and is",
            f"# imported lazily by the one module that needs it. Python {python}.",
            "",
            *core,
        ]
    )

    # -- development: core plus the test and lint tooling -------------------
    files["requirements-dev.txt"] = _block(
        [
            HEADER,
            "# Everything needed to run the test suite and the linter.",
            "#",
            "# With this installed, `pytest` works without installing the package at",
            "# all — pyproject.toml puts src/ on the test path. See the README's",
            "# 'Three ways to work with the code'.",
            "",
            "-r requirements.txt",
            "",
            *sorted(extras.get("dev", [])),
        ]
    )

    # -- the tutorial notebook ----------------------------------------------
    files["requirements-tutorial.txt"] = _block(
        [
            HEADER,
            "# For docs/tutorial.ipynb. The notebook itself needs only the core plus",
            "# Jupyter; nbformat and nbclient are for *rebuilding* it with",
            "# docs/build_tutorial.py, which executes every cell.",
            "",
            "-r requirements.txt",
            "",
            *sorted(extras.get("tutorial", [])),
        ]
    )

    # -- the optional extras, as one annotated menu -------------------------
    # Five near-empty files would be worse than one file you read and uncomment.
    notes = {
        "timeseries": "the darts forecasting handler and the TimeSeries adapter",
        "text": "text perturbations (character noise, token masking, word dropout)",
        "explain": "error attribution — the surrogate, SHAP values, tsfresh features",
        "safetycage": "model-centric robustness metrics (survey §5.2)",
        "mpl": "matplotlib, for the partial-dependence path only",
    }
    lines = [
        HEADER,
        "# The optional extras. Everything here is commented out: the core runs",
        "# without any of it, and each one pulls in a substantial dependency tree.",
        "#",
        "# Uncomment what you need, then:  pip install -r requirements-optional.txt",
        "# Or install the extra directly:  pip install -e \".[timeseries]\"",
        "#",
        "# Note that darts and safetycage have pinned transitive dependencies that",
        "# may not co-exist in one environment. Install the extras you actually use.",
        "",
        "-r requirements.txt",
    ]
    for name in sorted(extras):
        if name in ("dev", "tutorial"):
            continue  # each has its own file
        lines += ["", f"# [{name}] — {notes.get(name, '')}".rstrip()]
        lines += [f"# {requirement}" for requirement in extras[name]]
    files["requirements-optional.txt"] = _block(lines)

    # -- conda --------------------------------------------------------------
    # Everything comes from conda-forge and there is no `pip:` section at all. That is
    # deliberate, and it is the opposite of the first version of this file.
    #
    # Conda flattens a `pip:` list into one temporary requirements file and runs
    # `pip install -U -r` on it, which means (a) every wheel comes from PyPI, and (b) one
    # truncated download fails the whole `conda env create`. On a corporate network that
    # inspects or proxies TLS, a partial read of the numpy or scipy wheel is common, and
    # the error surfaces only as `CondaEnvException: Pip failed`.
    #
    # conda-forge is a different index reached by a different downloader, so letting conda
    # fetch the scientific stack removes pip from the critical path. `hatchling` and
    # `editables` are included because they are what building the editable install needs:
    # with both already present, `pip install -e . --no-deps --no-build-isolation` touches
    # the network zero times.
    conda_specs = _conda_specs(core, extras)
    files["environment.yml"] = _block(
        [
            "# GENERATED by tools/sync_requirements.py from pyproject.toml — do not edit.",
            "#",
            "#   conda env create -f environment.yml",
            "#   conda activate themis-assess",
            "#   pip install -e . --no-deps --no-build-isolation",
            "#",
            "# That last command installs the package as a *link* to src/, so edits take",
            "# effect immediately. It is a separate step on purpose: with hatchling and",
            "# editables already installed below, it needs no network at all, whereas a",
            "# `pip:` section here would put every wheel back on PyPI and let one",
            "# truncated download fail the whole environment.",
            "#",
            "# Without the link, `pytest` still works (pyproject.toml puts src/ on the",
            "# test path), but `import themis_assess` from a notebook or from a script in",
            "# another directory does not.",
            "#",
            "# Versions are generated from pyproject.toml, so the conda specs and the",
            "# requirements files cannot disagree. If conda-forge is missing a package,",
            "# drop it from here and `pip install` it after activating.",
            "name: themis-assess",
            "channels:",
            "  - conda-forge",
            "dependencies:",
            f"  - python>={python.lstrip('>=')}",
            "  - pip",
            *[f"  - {spec}" for spec in conda_specs],
        ]
    )
    return files


def main(check: bool = False) -> int:
    files = render(load())
    stale: list[str] = []
    for name, content in files.items():
        path = ROOT / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        stale.append(name)
        if not check:
            path.write_text(content, encoding="utf-8")

    if check:
        if stale:
            print("out of date:", ", ".join(stale))
            print("run: python tools/sync_requirements.py")
            return 1
        print(f"{len(files)} file(s) up to date")
        return 0

    if stale:
        print("wrote:", ", ".join(stale))
    else:
        print(f"{len(files)} file(s) already up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(check="--check" in sys.argv))
